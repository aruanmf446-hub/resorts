export type UiKey = keyof (typeof ui)['en'];
export type Locale = 'en' | 'pt-BR' | 'es';

export function useT(locale: Locale) {
  const dict = (ui as Record<string, Record<string, string>>)[locale] ?? ui.en;
  return (key: UiKey, vars?: Record<string, string | number>) => {
    let s = dict[key] ?? ui.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

/** Subset shipped to the browser for interactive components. */
export function clientStrings(locale: Locale, keys: UiKey[]) {
  const t = useT(locale);
  return Object.fromEntries(keys.map((k) => [k, t(k)]));
}

